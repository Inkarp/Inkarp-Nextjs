function getDateStrings(webinarOrDate) {
  if (typeof webinarOrDate === "string") {
    return [webinarOrDate];
  }

  if (Array.isArray(webinarOrDate?.dates) && webinarOrDate.dates.length) {
    return webinarOrDate.dates;
  }

  return webinarOrDate?.date ? [webinarOrDate.date] : [];
}

function toStartOfDay(value) {
  const date = new Date(value);
  date.setHours(0, 0, 0, 0);
  return date;
}

export function getUpcomingWebinarDate(webinarOrDate, todayValue = new Date()) {
  const today = toStartOfDay(todayValue);
  const dates = getDateStrings(webinarOrDate)
    .map((dateString) => toStartOfDay(dateString))
    .filter((date) => !Number.isNaN(date.getTime()))
    .sort((a, b) => a - b);

  return dates.find((date) => date >= today) ?? null;
}

export function getWebinarSortDate(webinar, todayValue = new Date()) {
  return getUpcomingWebinarDate(webinar, todayValue) ?? toStartOfDay(webinar.date);
}

export function getDaysLeft(webinarOrDate, todayValue = new Date()) {
  const today = toStartOfDay(todayValue);
  const target = getUpcomingWebinarDate(webinarOrDate, today);

  if (!target) {
    return 0;
  }

  today.setHours(0, 0, 0, 0);
  const diff = target - today;
  if (diff < 0) {
    return 0;
  }
  return Math.ceil(diff / (1000 * 60 * 60 * 24));
}

export function getUpcomingWebinarsCount() {
  return webinars.filter((webinar) => getDaysLeft(webinar) > 0).length;
}
